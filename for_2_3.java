package BT;
public class for_2_3 {
    public static void main(String[] args) {
        int so = 172;
        int tich;
        int i;
        tich = so * 10;
        for (i = 1;i >= 1 && i <= 10;i++){
            tich = so * i;
            System.out.println(so + "x" + i + " = " + tich);
       }
    }
}